// 多精度十进制数。
// 仅用于浮点数格式化，不是通用 decimal 实现。
// 仅支持赋值以及二进制左移/右移操作。
// 可以用多精度十进制精确表示二进制浮点数，
// 因为 2 可以整除 10；但是不能用多精度二进制精确表示十进制浮点数，
// 原因是十进制小数不一定能被二进制精确表达。

package decimal

type decimal struct {
	d     [800]byte // 数字数组，高位在前
	nd    int       // 已使用的数字个数
	dp    int       // 小数点位置
	neg   bool      // 负数标记
	trunc bool      // d[:nd] 之外是否丢弃过非零数字
}

func (a *decimal) String() string {
	n := 10 + a.nd
	if a.dp > 0 {
		n += a.dp
	}
	if a.dp < 0 {
		n += -a.dp
	}

	buf := make([]byte, n)
	w := 0
	switch {
	case a.nd == 0:
		return "0"

	case a.dp <= 0:
		// 小数点和有效数字之间用 0 填充
		buf[w] = '0'
		w++
		buf[w] = '.'
		w++
		w += digitZero(buf[w : w+-a.dp])
		w += copy(buf[w:], a.d[0:a.nd])

	case a.dp < a.nd:
		// 小数点位于有效数字中间
		w += copy(buf[w:], a.d[0:a.dp])
		buf[w] = '.'
		w++
		w += copy(buf[w:], a.d[a.dp:a.nd])

	default:
		// 有效数字和小数点之间用 0 填充
		w += copy(buf[w:], a.d[0:a.nd])
		w += digitZero(buf[w : w+a.dp-a.nd])
	}
	return string(buf[0:w])
}

func digitZero(dst []byte) int {
	for i := range dst {
		dst[i] = '0'
	}
	return len(dst)
}

// 去掉数字末尾多余的 0。
// 这些 0 没有实际意义；小数点位置是单独记录的，
// 不依赖当前保存了多少位数字。
func trim(a *decimal) {
	for a.nd > 0 && a.d[a.nd-1] == '0' {
		a.nd--
	}
	if a.nd == 0 {
		a.dp = 0
	}
}

// 把 v 赋值给 a。
func (a *decimal) Assign(v uint64) {
	var buf [24]byte

	// 把十进制数字倒序写入 buf。
	n := 0
	for v > 0 {
		v1 := v / 10
		v -= 10 * v1
		buf[n] = byte(v + '0')
		n++
		v = v1
	}

	// 再次反转，生成正序十进制数字并写入 a.d。
	a.nd = 0
	for n--; n >= 0; n-- {
		a.d[a.nd] = buf[n]
		a.nd++
	}
	a.dp = a.nd
	trim(a)
}

// 单次处理时，在不溢出的情况下允许的最大位移。
// uint 可能是 32 位或 64 位，同时必须能容纳 9<<k。
const uintSize = 32 << (^uint(0) >> 63)
const maxShift = uintSize - 4

// 二进制右移 k 位，相当于除以 2^k。k <= maxShift 用于避免溢出。
func rightShift(a *decimal, k uint) {
	r := 0 // read pointer；读指针
	w := 0 // write pointer；写指针

	// 先取足够多的前导数字，以完成第一次移位。
	var n uint
	for ; n>>k == 0; r++ {
		if r >= a.nd {
			if n == 0 {
				// a == 0；理论上不该走到这里，但仍然做保护处理。
				a.nd = 0
				return
			}
			for n>>k == 0 {
				n = n * 10
				r++
			}
			break
		}
		c := uint(a.d[r])
		n = n*10 + c - '0'
	}
	a.dp -= r - 1

	var mask uint = (1 << k) - 1

	// 取一个数字，写出一个数字。
	for ; r < a.nd; r++ {
		c := uint(a.d[r])
		dig := n >> k
		n &= mask
		a.d[w] = byte(dig + '0')
		w++
		n = n*10 + c - '0'
	}

	// 写出额外生成的数字。
	for n > 0 {
		dig := n >> k
		n &= mask
		if w < len(a.d) {
			a.d[w] = byte(dig + '0')
			w++
		} else if dig > 0 {
			a.trunc = true
		}
		n = n * 10
	}

	a.nd = w
	trim(a)
}

