// 判断 b 的前导前缀按字典序是否小于 s。
func prefixIsLessThan(b []byte, s string) bool {
	for i := 0; i < len(s); i++ {
		if i >= len(b) {
			return true
		}
		if b[i] != s[i] {
			return b[i] < s[i]
		}
	}
	return false
}

// 二进制左移 k 位，相当于乘以 2^k。k <= maxShift 用于避免溢出。
func leftShift(a *decimal, k uint) {
	delta := leftcheats[k].delta
	if prefixIsLessThan(a.d[0:a.nd], leftcheats[k].cutoff) {
		delta--
	}

	r := a.nd         // 读下标
	w := a.nd + delta // 写下标

	// 取一个数字，写出一个数字。
	var n uint
	for r--; r >= 0; r-- {
		n += (uint(a.d[r]) - '0') << k
		quo := n / 10
		rem := n - 10*quo
		w--
		if w < len(a.d) {
			a.d[w] = byte(rem + '0')
		} else if rem != 0 {
			a.trunc = true
		}
		n = quo
	}

	// 写出额外生成的数字。
	for n > 0 {
		quo := n / 10
		rem := n - 10*quo
		w--
		if w < len(a.d) {
			a.d[w] = byte(rem + '0')
		} else if rem != 0 {
			a.trunc = true
		}
		n = quo
	}

	a.nd += delta
	if a.nd >= len(a.d) {
		a.nd = len(a.d)
	}
	a.dp += delta
	trim(a)
}

// 根据 k 的正负进行二进制左移或右移：k > 0 左移，k < 0 右移。
func (a *decimal) Shift(k int) {
	switch {
	case a.nd == 0:
		// 无需处理，a == 0。
	case k > 0:
		for k > maxShift {
			leftShift(a, maxShift)
			k -= maxShift
		}
		leftShift(a, uint(k))
	case k < 0:
		for k < -maxShift {
			rightShift(a, maxShift)
			k += maxShift
		}
		rightShift(a, uint(-k))
	}
}

// 如果把 a 截断到 nd 位，是否应该向上舍入？
func shouldRoundUp(a *decimal, nd int) bool {
	if nd < 0 || nd >= a.nd {
		return false
	}
	if a.d[nd] == '5' && nd+1 == a.nd {
		// 正好在中间，按偶数舍入

		// 如果之前发生过截断，实际值比记录值略大，因此总是向上舍入。
		if a.trunc {
			return true
		}
		return nd > 0 && (a.d[nd-1]-'0')%2 != 0
	}

	// 不是正好一半时，只看当前位数字即可判断。
	return a.d[nd] >= '5'
}

// 把 a 舍入到 nd 位数字，或者更少。
// 如果 nd 为 0，表示舍入到所有数字左边的位置，
// 例如：
// 0.09 -> 0.1.
func (a *decimal) Round(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}
	if shouldRoundUp(a, nd) {
		a.RoundUp(nd)
	} else {
		a.RoundDown(nd)
	}
}

// 把 a 向下舍入到 nd 位数字，或者更少。
func (a *decimal) RoundDown(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}
	a.nd = nd
	trim(a)
}

// 把 a 向上舍入到 nd 位数字，或者更少。
func (a *decimal) RoundUp(nd int) {
	if nd < 0 || nd >= a.nd {
		return
	}

	// 执行向上舍入。
	for i := nd - 1; i >= 0; i-- {
		c := a.d[i]
		if c < '9' {
			// 这一位加 1 后即可停止
			a.d[i]++
			a.nd = i + 1
			return
		}
	}

	// 数字全部都是 9。
	// 改成单个 1，并调整小数点位置。
	a.d[0] = '1'
	a.nd = 1
	a.dp++
}

// 提取整数部分，并按需要进行舍入。
// 不保证不会溢出。
func (a *decimal) RoundedInteger() uint64 {
	if a.dp > 20 {
		return 0xFFFFFFFFFFFFFFFF
	}
	var i int
	n := uint64(0)
	for i = 0; i < a.dp && i < a.nd; i++ {
		n = n*10 + uint64(a.d[i]-'0')
	}
	for ; i < a.dp; i++ {
		n *= 10
	}
	if shouldRoundUp(a, a.dp) {
		n++
	}
	return n
}
